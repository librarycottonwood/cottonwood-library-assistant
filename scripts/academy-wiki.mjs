// Keep the assistant's bundled reference identical to the public academy content.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { academyUrl, reviewed, academyGroups, lessons, services, serviceGroups, quickReference } from '../src/pages/academy/_guide.ts';
const target = new URL('../plugins/cottonwood-library/skills/wiki/references/academy.md', import.meta.url);
const absolute = href => href.startsWith('/') ? new URL(href, academyUrl).href : href;
const lines = ['# Complete volunteer academy reference', '', '<!-- Generated by pnpm academy:wiki from src/pages/academy/_guide.ts. Edit the source, then regenerate. -->', '', `Content reviewed: ${reviewed}. These are lesson instructions, not proof of current account access or publication.`, '', '## Find a lesson', '', `- Overview: ${academyUrl}`];
for (const group of academyGroups) {
  lines.push('', `### ${group.title}`, '');
  for (const slug of group.slugs) {
    const lesson = lessons.find(item => item.slug === slug);
    lines.push(`- [${lesson.title}](${academyUrl}${slug}/): ${lesson.summary}`);
  }
}
lines.push('', `- Quick guide: ${academyUrl}quick-reference/`, `- Printable handbook: ${academyUrl}print/`, '', '## Academy buttons and navigation', '', 'The left menu groups lessons into Start here, Library tasks and Behind the scenes. On a phone, Browse lessons opens that menu. On this page lists sections and marks the section currently being read. Previous and Next links move between lessons.', '', 'The header has Library website, Print and Open ChatGPT. Print offers the quick guide and the full handbook. Each example has Open in ChatGPT, which opens a new tab with a prefilled Work message, and Copy. The volunteer reads or edits the message, then sends it. Square brackets in an example are placeholders for their own details. Opening an example does not publish a website change.', '');
for (const lesson of lessons) {
  lines.push(`## ${lesson.title}`, '', `Page: ${academyUrl}${lesson.slug}/`, '', lesson.summary, '');
  for (const part of lesson.parts) {
    lines.push(`### ${part.title}`, '');
    if (part.id) lines.push(`Section: ${academyUrl}${lesson.slug}/#${part.id}`, '');
    const addImages = images => lines.push(...images.flatMap(image => [`Screenshot: ${image.caption ?? image.alt}`, ...(image.caption ? ['', `Image description: ${image.alt}`] : []), '']));
    part.text.forEach((text, index) => {
      lines.push(text, '');
      addImages((part.screenshots ?? []).filter(image => image.afterParagraph === index + 1));
    });
    addImages((part.screenshots ?? []).filter(image => !image.beforeStep && !image.afterParagraph));
    if (part.items) lines.push(...part.items.flatMap(item => [`**${item.label}:** ${item.text}`, '']));
    if (part.prompt) lines.push('Example message:', '', `> ${part.prompt}`, '');
    part.steps?.forEach((step, index) => {
      addImages((part.screenshots ?? []).filter(image => image.beforeStep === index + 1));
      lines.push(`${index + 1}. ${step}`, '');
    });
    if (part.links) lines.push(...part.links.map(link => `- [${link.label}](${absolute(link.href)})`), '');
  }
  if (['accounts-and-tools', 'website-systems'].includes(lesson.slug)) {
    for (const group of serviceGroups.filter(group => lesson.slug === 'accounts-and-tools' ? group.id === 'daily' : group.id !== 'daily')) {
      lines.push(`### ${group.title}`, '');
      for (const service of services.filter(service => service.group === group.id)) {
        lines.push(`#### ${service.name}`, '', service.purpose, '', service.signin, '', `[${service.label}](${service.href})`, '');
      }
    }
  }
}
lines.push('## Quick guide', '', ...quickReference.flatMap(([title, text]) => [`### ${title}`, '', text, '']));
const content = lines.join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== content) throw new Error('Academy wiki is out of date. Run pnpm academy:wiki.');
  console.log('Academy wiki matches all lessons, examples, services and quick-guide entries.');
} else {
  await writeFile(target, content);
  console.log(`Updated ${fileURLToPath(target)}`);
}
